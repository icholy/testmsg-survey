// Command report aggregates survey results into a Markdown report.
//
// Usage:
//
//	go run ./cmd/report results > results/report.md
//
// It reads results/<tier>/*/summary.json for every tier directory.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"

	"github.com/icholy/testmsg-survey/internal/checks"
)

// minChecks is the minimum number of checks for a repository to be included
// in the per-repository distribution.
const minChecks = 20

type repoSummary struct {
	Tier   string `json:"tier"`
	Repo   string `json:"repo"`
	Commit string `json:"commit"`
	Error  string `json:"error,omitempty"`
	checks.Summary
}

func main() {
	log.SetFlags(0)
	flag.Parse()
	root := "results"
	if flag.NArg() > 0 {
		root = flag.Arg(0)
	}
	tiers, err := os.ReadDir(root)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Println("# Results")
	fmt.Println()
	fmt.Println("Generated by `go run ./cmd/report`. Percentages are the bare share of")
	fmt.Println("error checks. \"Pooled\" counts every check in the tier; \"median repo\" is")
	fmt.Printf("the median of per-repository shares, over repositories with at least %d\n", minChecks)
	fmt.Println("checks.")
	for _, t := range tiers {
		if !t.IsDir() {
			continue
		}
		sums, err := load(filepath.Join(root, t.Name()))
		if err != nil {
			log.Fatal(err)
		}
		report(t.Name(), sums)
	}
}

func load(dir string) ([]repoSummary, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "*", "summary.json"))
	if err != nil {
		return nil, err
	}
	var sums []repoSummary
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		var s repoSummary
		if err := json.Unmarshal(data, &s); err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
		sums = append(sums, s)
	}
	return sums, nil
}

type counts struct{ bare, ctx int }

func (c counts) total() int { return c.bare + c.ctx }

func (c counts) String() string {
	if c.total() == 0 {
		return "0 | 0 | -"
	}
	return fmt.Sprintf("%d | %d | %.1f%%", c.bare, c.ctx, 100*float64(c.bare)/float64(c.total()))
}

func (c *counts) add(o checks.Counts) {
	c.bare += o.Bare
	c.ctx += o.Contextual
}

func (c *counts) sub(o checks.Counts) {
	c.bare -= o.Bare
	c.ctx -= o.Contextual
}

func report(tier string, sums []repoSummary) {
	var (
		all, noEx  counts
		byMech     = map[checks.Mechanism]*counts{}
		byFunc     = map[string]*counts{}
		errored    []string
		withChecks int
		testFiles  int
		parseErrs  int
		unresolved int
		sharesAll  []float64
		sharesNoEx []float64
	)
	for _, s := range sums {
		if s.Error != "" {
			errored = append(errored, s.Repo)
			continue
		}
		testFiles += s.TestFiles
		parseErrs += len(s.TestParseErrors)
		unresolved += s.UnresolvedN
		var c, ce counts
		c.add(s.Total)
		ce.add(s.Total)
		ce.sub(s.ByFunc["example"])
		all.bare += c.bare
		all.ctx += c.ctx
		noEx.bare += ce.bare
		noEx.ctx += ce.ctx
		if c.total() > 0 {
			withChecks++
		}
		if c.total() >= minChecks {
			sharesAll = append(sharesAll, float64(c.bare)/float64(c.total()))
		}
		if ce.total() >= minChecks {
			sharesNoEx = append(sharesNoEx, float64(ce.bare)/float64(ce.total()))
		}
		for m, mc := range s.ByMechanism {
			if byMech[m] == nil {
				byMech[m] = &counts{}
			}
			byMech[m].add(mc)
		}
		for f, fc := range s.ByFunc {
			if byFunc[f] == nil {
				byFunc[f] = &counts{}
			}
			byFunc[f].add(fc)
		}
	}
	fmt.Printf("\n## %s\n\n", tier)
	fmt.Printf("- Repositories: %d (%d with at least one check, %d failed)\n", len(sums), withChecks, len(errored))
	fmt.Printf("- Test files: %d (%d failed to parse)\n", testFiles, parseErrs)
	fmt.Printf("- Unresolved calls: %d\n", unresolved)
	if len(errored) > 0 {
		sort.Strings(errored)
		fmt.Printf("- Failed: %v\n", errored)
	}
	fmt.Println()
	fmt.Println("| Scope | Bare | Contextual | Bare % (pooled) | Bare % (median repo) |")
	fmt.Println("| --- | --- | --- | --- | --- |")
	fmt.Printf("| All checks | %s | %s |\n", all, median(sharesAll))
	fmt.Printf("| Excluding examples | %s | %s |\n", noEx, median(sharesNoEx))
	fmt.Println()
	fmt.Println("| Mechanism | Bare | Contextual | Bare % |")
	fmt.Println("| --- | --- | --- | --- |")
	for _, m := range []checks.Mechanism{checks.Direct, checks.Library, checks.Helper, checks.Panic} {
		c := byMech[m]
		if c == nil {
			c = &counts{}
		}
		fmt.Printf("| %s | %s |\n", m, c)
	}
	fmt.Println()
	fmt.Println("| Function kind | Bare | Contextual | Bare % |")
	fmt.Println("| --- | --- | --- | --- |")
	for _, f := range []string{"test", "benchmark", "fuzz", "example", "other"} {
		c := byFunc[f]
		if c == nil {
			c = &counts{}
		}
		fmt.Printf("| %s | %s |\n", f, c)
	}
}

func median(xs []float64) string {
	if len(xs) == 0 {
		return "-"
	}
	sort.Float64s(xs)
	n := len(xs)
	m := xs[n/2]
	if n%2 == 0 {
		m = (xs[n/2-1] + xs[n/2]) / 2
	}
	return fmt.Sprintf("%.1f%% (n=%d)", 100*m, n)
}
